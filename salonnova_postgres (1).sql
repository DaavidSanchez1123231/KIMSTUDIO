-- Convertido desde la base EsteticaKIM de SQL Server (base_de_datos_kim.ipynb)
--
-- Uso:
--   createdb -U postgres salonnova
--   psql -U postgres -d salonnova -f salonnova_postgres.sql
--
-- Equivalencias: IDENTITY -> IDENTITY, BIT -> BOOLEAN, DATETIME -> TIMESTAMP,
-- NVARCHAR(MAX) -> TEXT, UNIQUEIDENTIFIER -> UUID, GETDATE() -> NOW(),
-- procedimientos almacenados -> funciones (se llaman con SELECT * FROM sp_x(...)).
-- =====================================================================
SET client_encoding = 'UTF8';

