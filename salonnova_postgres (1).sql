-- ============================ TABLAS =================================
CREATE TABLE usuarios (
  id_usuario          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre              VARCHAR(50),
  email               VARCHAR(50) UNIQUE,
  contraseña          VARCHAR(80),
  rol                 VARCHAR(20) DEFAULT 'cliente',
  cuenta_verificada   BOOLEAN DEFAULT FALSE,
  token_verificacion  UUID,
  fecha_registro      TIMESTAMP DEFAULT NOW(),
  telefono            VARCHAR(9),
  CONSTRAINT chk_rol CHECK (rol IN ('cliente', 'recepcion', 'admin'))
);
-- El correo no distingue mayúsculas (como en SQL Server)
CREATE UNIQUE INDEX uq_usuarios_email_lower ON usuarios (LOWER(email));

CREATE TABLE especialistas (
  id_especialista INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(50),
  especialidad    VARCHAR(50),
  estado          BOOLEAN DEFAULT TRUE,
  telefono        VARCHAR(9)
);

CREATE TABLE servicios (
  id_servicio      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(50),
  descripcion      TEXT,
  precio           NUMERIC(10,2),
  duracion_minutos INTEGER,
  imagen_url       TEXT,
  categoria        VARCHAR(50) DEFAULT 'cabello',
  estado           BOOLEAN DEFAULT TRUE
);

CREATE TABLE horarios (
  id_horario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_especialista INTEGER,
  fecha           DATE,
  hora_inicio     TIME,
  hora_fin        TIME,
  estado          VARCHAR(20) DEFAULT 'DISPONIBLE',
  fecha_bloqueo   TIMESTAMP,
  CONSTRAINT fk_horarios_especialista FOREIGN KEY (id_especialista) REFERENCES especialistas (id_especialista)
);

CREATE TABLE citas (
  id_cita         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INTEGER,
  id_especialista INTEGER,
  id_servicio     INTEGER,
  id_horario      INTEGER,
  estado          VARCHAR(30) DEFAULT 'pendiente_confirmacion',
  fecha_creacion  TIMESTAMP DEFAULT NOW(),
  CONSTRAINT fk_citas_usuario      FOREIGN KEY (id_usuario)      REFERENCES usuarios (id_usuario),
  CONSTRAINT fk_citas_especialista FOREIGN KEY (id_especialista) REFERENCES especialistas (id_especialista),
  CONSTRAINT fk_citas_servicio     FOREIGN KEY (id_servicio)     REFERENCES servicios (id_servicio),
  CONSTRAINT fk_citas_horario      FOREIGN KEY (id_horario)      REFERENCES horarios (id_horario)
);

CREATE TABLE promociones (
  id_promocion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(100) NOT NULL,
  descuento        INTEGER NOT NULL CHECK (descuento > 0 AND descuento <= 100),
  codigo           VARCHAR(50) NOT NULL UNIQUE,
  fecha_expiracion DATE NOT NULL,
  descripcion      VARCHAR(255),
  estado           BOOLEAN DEFAULT TRUE
);

CREATE TABLE productos (
  id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL,
  categoria   VARCHAR(50),
  precio      NUMERIC(10,2) NOT NULL,
  stock       INTEGER NOT NULL CHECK (stock >= 0),
  descripcion VARCHAR(255),
  estado      BOOLEAN DEFAULT TRUE
);

CREATE TABLE ventas (
  id_venta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente   INTEGER,
  id_cita      INTEGER,
  id_promocion INTEGER,
  metodo_pago  VARCHAR(50) CHECK (metodo_pago IN ('Yape', 'Tarjeta', 'Efectivo')),
  monto_total  NUMERIC(10,2) NOT NULL,
  fecha_venta  TIMESTAMP DEFAULT NOW(),
  CONSTRAINT fk_ventas_cliente   FOREIGN KEY (id_cliente)   REFERENCES usuarios (id_usuario),
  CONSTRAINT fk_ventas_cita      FOREIGN KEY (id_cita)      REFERENCES citas (id_cita),
  CONSTRAINT fk_ventas_promocion FOREIGN KEY (id_promocion) REFERENCES promociones (id_promocion)
);

CREATE TABLE detalle_venta_producto (
  id_detalle      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta        INTEGER,
  id_producto     INTEGER,
  cantidad        INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10,2) NOT NULL,
  CONSTRAINT fk_detalle_venta    FOREIGN KEY (id_venta)    REFERENCES ventas (id_venta),
  CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES productos (id_producto)
);

CREATE TABLE galeria (
  id_imagen    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo       VARCHAR(100),
  categoria    VARCHAR(50) DEFAULT 'General',
  url_imagen   VARCHAR(500) NOT NULL,
  fecha_subida TIMESTAMP DEFAULT NOW(),
  estado       BOOLEAN DEFAULT TRUE
);

CREATE TABLE configuracion (
